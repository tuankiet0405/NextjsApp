-- Run in Supabase: SQL Editor -> paste -> Run. Then run seed.sql.
-- Mirrors the production schema; later changes live in supabase/migrations/.

create extension if not exists btree_gist;

create table if not exists public.settings (
  id                   bigint generated by default as identity primary key,
  created_at           timestamptz not null default now(),
  "minBookingLength"   int not null default 2  check ("minBookingLength" >= 1),
  "maxBookingLength"   int not null default 30 check ("maxBookingLength" >= "minBookingLength"),
  "maxGuestPerBooking"  int not null default 10,
  "breakfastPrice"     numeric(10,2) not null default 15 check ("breakfastPrice" >= 0)
);

create table if not exists public.cabins (
  id             bigint generated by default as identity primary key,
  created_at     timestamptz not null default now(),
  name           text not null unique,
  "maxCapacity"  int not null check ("maxCapacity" > 0),
  "regularPrice" numeric(10,2) not null check ("regularPrice" >= 0),
  discount       numeric(10,2) not null default 0 check (discount >= 0),
  description    text,
  image          text not null,
  images         jsonb default '[]'::jsonb,
  constraint discount_le_price check (discount <= "regularPrice")
);

create table if not exists public.guests (
  id                 bigint generated by default as identity primary key,
  created_at         timestamptz not null default now(),
  "fullName"         text not null,
  email              text not null unique,
  "nationalID"       text,
  nationality        text,
  "countryFlag"      text,
  password           text,               -- bcrypt hash, null for OAuth-only guests
  "policyAccepted"   boolean default false,
  "policyAcceptedAt" timestamptz,
  role               text not null default 'guest' check (role in ('guest', 'admin'))
);

create table if not exists public.bookings (
  id             bigint generated by default as identity primary key,
  created_at     timestamptz not null default now(),
  "startDate"    timestamp not null,  -- calendar day at 00:00, no timezone
  "endDate"      timestamp not null,
  "numNights"    int not null check ("numNights" > 0),
  "numGuests"    int not null check ("numGuests" > 0),
  "cabinPrice"   numeric(10,2) not null,
  "extrasPrice"  numeric(10,2) not null default 0,
  "totalPrice"   numeric(10,2) not null,
  status         text not null default 'unconfirmed'
                 check (status in ('unconfirmed', 'checked-in', 'checked-out')),
  "hasBreakfast" boolean not null default false,
  "isPaid"       boolean not null default false,
  observations   text,
  "cabinId"      bigint not null references public.cabins(id) on delete cascade,
  "guestId"      bigint not null references public.guests(id) on delete cascade,
  constraint end_after_start check ("endDate" > "startDate"),
  -- Database-level guarantee against double booking (also covers race conditions).
  constraint no_overlapping_bookings exclude using gist (
    "cabinId" with =,
    tsrange("startDate", "endDate", '[)') with &&
  )
);
create index if not exists bookings_guest_idx on public.bookings ("guestId");

create table if not exists public.reviews (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  "guestId"   bigint not null references public.guests(id) on delete cascade,
  "cabinId"   bigint not null references public.cabins(id) on delete cascade,
  "bookingId" bigint not null unique references public.bookings(id) on delete cascade,
  rating      int not null check (rating between 1 and 5),
  comment     text check (char_length(comment) <= 2000)
);
create index if not exists reviews_cabin_idx on public.reviews ("cabinId");

create table if not exists public.favorites (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  "guestId"   bigint not null references public.guests(id) on delete cascade,
  "cabinId"   bigint not null references public.cabins(id) on delete cascade,
  unique ("guestId", "cabinId")
);

-- Row Level Security: the app talks to the DB only from the server with the
-- service_role key (which bypasses RLS). Enabling RLS with no policies means
-- the public anon key cannot read or write anything.
alter table public.settings  enable row level security;
alter table public.cabins    enable row level security;
alter table public.guests    enable row level security;
alter table public.bookings  enable row level security;
alter table public.reviews   enable row level security;
alter table public.favorites enable row level security;
